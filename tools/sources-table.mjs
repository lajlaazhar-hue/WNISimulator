// Regenerates docs/SOURCES.md from the data files: the source registry,
// every wage the game uses, and the status of every catalog price.
// Usage: node tools/sources-table.mjs
import { writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const require = createRequire(import.meta.url);
const manifest = require(join(root, 'src', 'manifest.json'));
for (const f of manifest.engine) require(join(root, f));
const { data: D, money: M } = globalThis.RLS;
const nm = (x) => (typeof x === 'string' ? x : x.en === x.id ? x.id : `${x.id} / ${x.en}`);
const link = (s) => (s.url ? `[${s.publisher}](${s.url})` : s.publisher);
const out = [];
out.push('# Source registry', '', '_Generated by `npm run sources` from `src/data/`. Do not edit by hand._', '');
out.push('Labels: **VERIFIED** supported by a cited source · **ESTIMATED** derived from a documented method · **ILLUSTRATIVE** gameplay value, not a real-world claim · **UNAVAILABLE** no reliable value.', '');
out.push('## Sources', '', '| id | Type | Source | Published | Checked | What it supports |', '|---|---|---|---|---|---|');
for (const s of D.sources) out.push(`| \`${s.id}\` | ${s.type} | ${link(s)}: ${s.title} | ${s.published} | ${s.accessed} | ${s.note.replace(/\|/g, '/')} |`);
out.push('', '## Provincial minimum wages (UMP) 2026', '', '| Province | UMP 2026 | Source | Note |', '|---|---:|---|---|');
for (const p of D.indonesia.provinces) out.push(`| ${p.name} | ${M.format(M.toMinor(p.wage.amountMajor), { exact: true })} | \`${p.wage.sourceId}\` | ${p.wage.note || ''} |`);
out.push('', '## City / regency minimum wages (UMK) 2026 loaded', '', '| City / regency | Province | UMK 2026 | Source | Note |', '|---|---|---:|---|---|');
for (const c of D.indonesia.cities.filter((x) => x.wage)) out.push(`| ${c.name} | ${D.indonesia.provinceById[c.provinceId].name} | ${M.format(M.toMinor(c.wage.amountMajor), { exact: true })} | \`${c.wage.sourceId}\` | ${c.wage.note || ''} |`);
out.push('', '## Localities using the UMP fallback', '', D.indonesia.cities.filter((x) => !x.wage).map((c) => `${c.name} (${D.indonesia.provinceById[c.provinceId].name})`).join(' · '), '');
out.push('## Catalog prices by status', '', '| Status | Count | Items |', '|---|---:|---|');
const by = {};
for (const i of D.catalog.items) (by[i.status] = by[i.status] || []).push(nm(i.name));
for (const [k, v] of Object.entries(by)) out.push(`| ${k} | ${v.length} | ${k === 'VERIFIED' || k === 'ESTIMATED' ? v.join('; ') : 'see src/data/catalog.js'} |`);
out.push('', '## Other sourced values', '', '| Value | Amount | Status | Source |', '|---|---|---|---|');
for (const d of D.travel.DOCS.filter((x) => x.status !== 'ILLUSTRATIVE' && !x.held)) out.push(`| ${nm(d.name)} | ${typeof d.fee === 'object' ? `${d.fee.cur} ${d.fee.amount}` : d.fee ? M.format(M.rp(d.fee)) : '—'} | ${d.status} | \`${d.sourceId}\` |`);
for (const t of D.travel.PASSPORT_TYPES) out.push(`| ${nm(t.name)} | ${M.format(M.rp(t.fee))} | VERIFIED | \`passport_fee_2024\` |`);
for (const l of D.lenders) out.push(`| ${nm(l.name)} | ${l.kind} | ${l.status} | \`${l.sourceId}\` |`);
out.push('', 'Fictional by design (source `fictional_brands`): every brand, employer, job listing, ride-hailing provider and lender. Trip costs, activity prices, child costs and most store prices are ILLUSTRATIVE gameplay values.', '');
writeFileSync(join(root, 'docs', 'SOURCES.md'), out.join('\n') + '\n');
console.log('Wrote docs/SOURCES.md');
